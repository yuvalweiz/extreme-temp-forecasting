"""FRAMING A numbers pack + AVP export for the NN-interpolation featured pipeline.
1. Exports 5-seed-ensemble AVP csvs for the NN variant (and the per-station Tab-TFT
   ablation) in the exact deliverable schema, into
   results/actual_vs_predicted_corrected/{season}/{region}/ as
   ConvNeXtTiny-TFT-NN__{anchor,soft}.csv and Tab-TFT__{anchor,soft}.csv.
2. Emits FRAMING_A_NUMBERS.md with every number the article edit needs
   (per region x target MAE/RMSE/UPE, both seasons, LOSO, significance counts).
Idempotent; re-run when more seeds land.  NOTE (winter): 'hot' columns in cold runs
are the COLDEST-day outputs; UPE direction flips (over-prediction is dangerous).
"""
import glob
import os
import numpy as np
import pandas as pd

E = "/home/weizyuv/expreal"
AVP = "/home/weizyuv/article /results/actual_vs_predicted_corrected"
TGTS = ["hot", "p3", "p7", "p15"]
COLS = ["tag"] + [f"pred_m1_{t}" for t in TGTS] + [f"true_m1_{t}" for t in TGTS]

SOURCES = {  # (model_name, season) -> region -> globs
  ("ConvNeXtTiny-TFT-NN", "summer"): {
    "Center": [f"{E}/Center_tune/nnfs2std_a1b0__*"],
    "Negev": [f"{E}/Negev_stable/nnfFIN_std__*"],
    "Northwest": [f"{E}/Northwest_stable/nnfFIN_std__*"]},
  ("ConvNeXtTiny-TFT-NN", "winter"): {
    r: [f"{E}/{r}_cold/nnfwin__*"] for r in ["Center", "Negev", "Northwest"]},
  ("Tab-TFT", "summer"): {
    "Center": [f"{E}/Center_tune/stfs2std_a1b0__*"],
    "Negev": [f"{E}/Negev_stable/stfSTDFIN__*"],
    "Northwest": [f"{E}/Northwest_stable/stfSTDFIN__*"]},
}

def ensemble(globs):
    fs = []
    for g in globs:
        for d in sorted(glob.glob(g)):
            f = os.path.join(d, "preds_test_topk.csv")
            if os.path.exists(f):
                fs.append(f)
    if not fs:
        return None, 0
    ens = pd.concat([pd.read_csv(f)[COLS] for f in fs]).groupby("tag", as_index=False).mean()
    return ens.sort_values("tag"), len(fs)

def export_avp(model, season, region, ens):
    d = f"{AVP}/{season}/{region}"
    os.makedirs(d, exist_ok=True)
    base = dict(date=ens.tag, region=region, season=season, model=model, split="test")
    a = pd.DataFrame(base)
    a["sample_id"] = region + f"_{season}_" + ens.tag.astype(str)
    a["target"] = "anchor"
    a["actual"] = ens.true_m1_hot.round(6)
    a["predicted"] = ens.pred_m1_hot.round(6)
    a["residual"] = (a.predicted - a.actual).round(6)
    a["abs_error"] = a.residual.abs().round(6)
    a["sq_error"] = (a.residual ** 2).round(6)
    order = ["sample_id", "date", "region", "season", "target", "model", "split",
             "actual", "predicted", "residual", "abs_error", "sq_error"]
    a[order].to_csv(f"{d}/{model}__anchor.csv", index=False)
    s = pd.DataFrame(base)
    s["sample_id"] = a["sample_id"]
    s["target"] = "soft"
    s["actual"] = ens.true_m1_p3.round(6)         # p3 kept as the schema's lead column
    s["predicted"] = ens.pred_m1_p3.round(6)
    s["residual"] = (s.predicted - s.actual).round(6)
    s["abs_error"] = s.residual.abs().round(6)
    s["sq_error"] = (s.residual ** 2).round(6)
    for k in (3, 7, 15):
        s[f"actual_p{k}"] = ens[f"true_m1_p{k}"].round(6)
        s[f"predicted_p{k}"] = ens[f"pred_m1_p{k}"].round(6)
    s[order + [c for k in (3, 7, 15) for c in (f"actual_p{k}", f"predicted_p{k}")]] \
        .to_csv(f"{d}/{model}__soft.csv", index=False)

def metrics(ens, season):
    out = {}
    for t in TGTS:
        e = ens[f"pred_m1_{t}"].to_numpy() - ens[f"true_m1_{t}"].to_numpy()
        upe = np.maximum(e, 0).mean() if season == "winter" else np.maximum(-e, 0).mean()
        out[t] = (float(np.abs(e).mean()), float(np.sqrt((e ** 2).mean())), float(upe))
    return out

lines = ["# FRAMING A NUMBERS PACK (auto-generated by gather_framingA.py)\n",
         "LOSO (max dry temp, test-period): NN 1.044 | kernel 1.183 | IDW ~1.71 | KED 0.909 (forecast-harmful)\n"]
for (model, season), regs in SOURCES.items():
    lines.append(f"\n## {model} — {season}")
    for reg, globs in regs.items():
        ens, n = ensemble(globs)
        if ens is None:
            lines.append(f"  {reg}: PENDING")
            continue
        export_avp(model, season, reg, ens)
        mm = metrics(ens, season)
        row = " | ".join(f"{t}: MAE {mm[t][0]:.3f} RMSE {mm[t][1]:.3f} UPE {mm[t][2]:.3f}" for t in TGTS)
        lines.append(f"  {reg} (n={n}): {row}")
open(f"{E}/FRAMING_A_NUMBERS.md", "w").write("\n".join(lines) + "\n")
print("\n".join(lines))
print("\nAVP exports written into results/actual_vs_predicted_corrected/.")
